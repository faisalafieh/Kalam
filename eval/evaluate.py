"""
Run Kalam's exact production pipeline over a test set and score it.

    python eval/evaluate.py --manifest eval/data/ami/manifest_headset.jsonl --tag ami-headset

Manifest: one JSON object per line. Paths are relative to the manifest file.
    {"id": "hearing01",
     "audio": "hearing01.m4a",
     "reference": "hearing01.txt",     # required
     "rttm": "hearing01.rttm",         # optional, enables DER
     "uem":  "hearing01.uem"}          # optional, scoring region for DER

Reference formats:
    .json  [{"speaker": "A", "text": "..."}, ...] in chronological order
    .txt   one utterance per line as "Speaker name: what they said".
           Lines without a "Name:" prefix are attributed to UNKNOWN.

Hypotheses are cached in eval/results/hyp/<tag>/. Re-running the same tag skips
files that are already transcribed (resume after a crash); --fresh redoes them.
Re-score cached transcripts without loading any model:
    python eval/evaluate.py --manifest ... --tag ... --rescore

Writes eval/results/<tag>.json and regenerates eval/RESULTS.md.
"""

import argparse
import json
import os
import platform
import subprocess
import sys
import tempfile
import time
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parent))

import metrics  # noqa: E402

# KALAM_RESULTS_DIR lets results live somewhere that survives a dropped session
# (e.g. Google Drive on Colab). Transcripts cached there are reused on re-runs.
RESULTS_DIR = Path(os.getenv("KALAM_RESULTS_DIR", HERE / "results"))


def load_reference(path: Path) -> list[dict]:
    if path.suffix == ".json":
        return json.loads(path.read_text())
    utts = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        speaker, sep, text = line.partition(":")
        if sep and len(speaker) <= 40:
            utts.append({"speaker": speaker.strip(), "text": text.strip()})
        else:
            utts.append({"speaker": "UNKNOWN", "text": line})
    return utts


def git_commit() -> str:
    try:
        return subprocess.check_output(
            ["git", "-C", str(HERE.parent), "rev-parse", "--short", "HEAD"], text=True
        ).strip()
    except Exception:
        return "unknown"


def pct(x: float) -> str:
    return "n/a" if x != x else f"{100 * x:.1f}%"


def write_results_md() -> None:
    runs = [json.loads(p.read_text()) for p in sorted(RESULTS_DIR.glob("*.json"))]
    lines = [
        "# Kalam evaluation results",
        "",
        "Generated by `eval/evaluate.py`. Do not edit by hand; re-run the script.",
        "",
        "- **WER**: word error rate, ignoring speakers (lower is better).",
        "- **cpWER**: speaker-attributed WER. Words credited to the wrong speaker count as errors.",
        "- **DER**: diarization error rate (missed speech + false alarm + speaker confusion), no collar, overlap included.",
        "- **RTF**: processing time / audio duration on the machine listed (below 1.0 is faster than real time).",
        "",
        "All rates are pooled over every reference word or second in the set, not averaged per file.",
        "",
        "| Test set | Files | Audio | WER | cpWER | DER | RTF | Model | Hardware | Commit | Date |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in runs:
        s = r["summary"]
        lines.append(
            f"| {r['tag']} | {s['files']} | {s['audio_hours']:.2f} h | {pct(s['wer'])} | "
            f"{pct(s['cpwer'])} | {pct(s['der'])} | {s['rtf']:.2f} | "
            f"whisper-{r['config']['whisper_model']} ({r['config']['compute_type']}, "
            f"beam {r['config'].get('beam_size', 1)}, lang {r['config'].get('language', 'auto')}, "
            f"{'separated streams' if r['config'].get('separation') else ('word' if r['config'].get('word_speakers') else 'segment') + '-level speakers'}) + "
            f"{'pyannote 3.1' if r['config']['diarization'] else 'no diarization'} | "
            f"{r['config']['hardware']} | {r['config']['commit']} | {r['date'][:10]} |"
        )
    for r in runs:
        lines += [
            "",
            f"## {r['tag']}",
            "",
            "| File | Minutes | Ref words | WER | Sub / Del / Ins | cpWER | DER | Speakers (ref / found) | Language |",
            "|---|---|---|---|---|---|---|---|---|",
        ]
        for f in r["files"]:
            w = f["wer"]
            lines.append(
                f"| {f['id']} | {f['duration'] / 60:.1f} | {f['wer']['ref_words']} | "
                f"{pct(f['wer_rate'])} | {w['sub']} / {w['del']} / {w['ins']} | "
                f"{pct(f['cpwer_rate'])} | {pct(f['der_rate'])} | "
                f"{f['cpwer']['ref_speakers']} / {f['cpwer']['hyp_speakers']} | {f.get('language', '?')} |"
            )
        s = r["summary"]
        w = s["wer_counts"]
        lines.append("")
        lines.append(
            f"WER breakdown: {w['sub']} substitutions, {w['del']} deletions, "
            f"{w['ins']} insertions over {w['ref_words']} reference words."
        )
        if s["der_counts"]["total"]:
            d = s["der_counts"]
            lines.append(
                f"DER breakdown: missed {pct(d['missed'] / d['total'])}, "
                f"false alarm {pct(d['false_alarm'] / d['total'])}, "
                f"confusion {pct(d['confusion'] / d['total'])}."
            )
    text = "\n".join(lines) + "\n"
    (HERE / "RESULTS.md").write_text(text)
    if RESULTS_DIR != HERE / "results":
        (RESULTS_DIR / "RESULTS.md").write_text(text)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--manifest", required=True)
    ap.add_argument("--tag", required=True, help="name for this run, e.g. ami-headset")
    ap.add_argument("--rescore", action="store_true", help="reuse cached hypotheses, skip inference")
    ap.add_argument("--fresh", action="store_true", help="ignore cached transcripts for this tag and redo them")
    ap.add_argument("--hardware", default=f"{platform.system()} {platform.machine()}, {os.cpu_count()} CPU threads",
                    help="free-text hardware description for the results table")
    args = ap.parse_args()

    manifest = Path(args.manifest).resolve()
    base = manifest.parent
    items = [json.loads(l) for l in manifest.read_text().splitlines() if l.strip()]
    hyp_dir = RESULTS_DIR / "hyp" / args.tag
    hyp_dir.mkdir(parents=True, exist_ok=True)

    import app  # the production module: same models, same settings, same code path

    models = {}

    def get_models():
        """Load models only when a file actually needs transcribing."""
        if not models:
            print(f"Loading whisper-{app.WHISPER_MODEL} on {app.DEVICE} ({app.COMPUTE_TYPE})...", flush=True)
            models["asr"], models["diar"] = app.load_models()
            if app.DIARIZE and models["diar"] is None:
                print("WARNING: diarization is off (no HF_TOKEN). cpWER will treat everything as one speaker.")
        return models["asr"], models["diar"]

    files = []
    tot = {k: {"sub": 0, "del": 0, "ins": 0, "ref_words": 0} for k in ("wer", "cpwer")}
    der_tot = {"total": 0.0, "missed": 0.0, "false_alarm": 0.0, "confusion": 0.0}
    audio_s = proc_s = 0.0
    diarized = False

    for it in items:
        cache = hyp_dir / f"{it['id']}.json"
        if args.rescore and not cache.exists():
            sys.exit(f"--rescore but no cached hypothesis for {it['id']}")
        if cache.exists() and not args.fresh:
            hyp = json.loads(cache.read_text())
            if not args.rescore:
                print(f"[{it['id']}] already transcribed, reusing", flush=True)
        else:
            asr, diar = get_models()
            print(f"[{it['id']}] transcribing...", flush=True)
            with tempfile.TemporaryDirectory() as tmp:
                wav = os.path.join(tmp, "audio.wav")
                t0 = time.perf_counter()
                app.to_wav(str(base / it["audio"]), wav)
                hyp = app.run_pipeline(wav, asr, diar)
                hyp["processing_seconds"] = time.perf_counter() - t0
            cache.write_text(json.dumps(hyp, indent=1))

        diarized = diarized or bool(hyp.get("turns"))
        ref = load_reference(base / it["reference"])
        wer_c = metrics.wer_counts(ref, hyp["segments"])
        cp_c = metrics.cpwer_counts(ref, hyp["segments"])
        der_c = None
        if it.get("rttm") and hyp.get("turns"):
            der_c = metrics.der_components(
                str(base / it["rttm"]), hyp["turns"], str(base / it["uem"]) if it.get("uem") else None
            )
            for k in der_tot:
                der_tot[k] += der_c[k]
        for k in ("sub", "del", "ins", "ref_words"):
            tot["wer"][k] += wer_c[k]
            tot["cpwer"][k] += cp_c[k]
        audio_s += hyp["duration"]
        proc_s += hyp.get("processing_seconds", 0.0)

        f = {
            "id": it["id"],
            "duration": hyp["duration"],
            "language": hyp.get("language"),
            "wer": wer_c,
            "wer_rate": metrics.rate(wer_c),
            "cpwer": cp_c,
            "cpwer_rate": metrics.rate(cp_c),
            "der": der_c,
            "der_rate": metrics.der_rate(der_c) if der_c else float("nan"),
        }
        files.append(f)
        print(
            f"[{it['id']}] WER {pct(f['wer_rate'])} (sub {wer_c['sub']} / del {wer_c['del']} / ins {wer_c['ins']})"
            f"  cpWER {pct(f['cpwer_rate'])}  DER {pct(f['der_rate'])}  lang {f['language']}"
        )

    config = {
        "whisper_model": app.WHISPER_MODEL,
        "compute_type": app.COMPUTE_TYPE,
        "language": app.LANGUAGE,
        "beam_size": app.BEAM_SIZE,
        "condition_on_previous_text": app.CONDITION_ON_PREVIOUS,
        "word_speakers": app.WORD_SPEAKERS,
        "separation": app.SEPARATE,
        "device": app.DEVICE,
        "diarization": diarized,
        "hardware": args.hardware,
        "commit": git_commit(),
    }
    summary = {
        "files": len(files),
        "audio_hours": audio_s / 3600,
        "wer": metrics.rate(tot["wer"]),
        "cpwer": metrics.rate(tot["cpwer"]),
        "der": metrics.der_rate(der_tot),
        "rtf": proc_s / audio_s if audio_s else float("nan"),
        "wer_counts": tot["wer"],
        "cpwer_counts": tot["cpwer"],
        "der_counts": der_tot,
    }
    result = {
        "tag": args.tag,
        "date": datetime.now(timezone.utc).isoformat(),
        "config": config,
        "summary": summary,
        "files": files,
    }
    (RESULTS_DIR / f"{args.tag}.json").write_text(json.dumps(result, indent=1))
    write_results_md()

    print(
        f"\n{args.tag}: WER {pct(summary['wer'])} | cpWER {pct(summary['cpwer'])} | "
        f"DER {pct(summary['der'])} | RTF {summary['rtf']:.2f} over {summary['audio_hours']:.2f} h"
    )
    print(f"Written: {RESULTS_DIR / (args.tag + '.json')} and {HERE / 'RESULTS.md'}")


if __name__ == "__main__":
    main()
